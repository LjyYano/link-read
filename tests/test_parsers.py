import pytest

from linkread_desktop.errors import ExtractionError, SubtitleUnavailableError
from linkread_desktop.parsers import parse_bilibili_json, parse_srt_vtt


def test_srt_timestamps_multiline_and_bom():
    source = "\ufeff1\r\n00:00:01,250 --> 00:00:03,000\r\nHello\r\nworld\r\n\r\n2\r\n00:00:04,000 --> 00:00:05,500\r\n你好\r\n"
    result = parse_srt_vtt(source)
    assert [(s.start_ms, s.end_ms, s.text) for s in result] == [
        (1250, 3000, "Hello world"),
        (4000, 5500, "你好"),
    ]


def test_vtt_header_settings_html_and_repeated_caption():
    source = """WEBVTT

NOTE generated by platform
Ignore me

00:00:00.000 --> 00:00:01.000 align:start
<c>Good</c>

00:00:00.500 --> 00:00:01.500
<c>Good</c>

00:00:01.000 --> 00:00:02.000
Good morning &amp; welcome
"""
    result = parse_srt_vtt(source)
    assert [s.text for s in result] == ["Good", "morning & welcome"]
    assert [s.start_ms for s in result] == [0, 1000]


@pytest.mark.parametrize("second_start", ["00:00:02,000", "00:00:03,000"])
@pytest.mark.parametrize(("first", "second"), [
    ("完全没问题", "完全没问题"),
    ("那么会出现什么情况", "会出现什么情况"),
    ("完全没问题", "完全没问题啊"),
])
def test_non_overlapping_spoken_repetitions_remain_complete(first, second, second_start):
    source = (f"1\n00:00:01,000 --> 00:00:02,000\n{first}\n\n"
              f"2\n{second_start} --> 00:00:04,000\n{second}\n")
    result = parse_srt_vtt(source)
    assert [cue.text for cue in result] == [first, second]
    assert result[0].end_ms == 2000
    assert result[1].start_ms == (2000 if second_start == "00:00:02,000" else 3000)
    assert result[1].end_ms == 4000


def test_rolling_snapshots_stop_deduplicating_after_display_interval():
    source = """WEBVTT

00:00:00.000 --> 00:00:02.000
Good morning

00:00:01.000 --> 00:00:03.000
morning

00:00:02.000 --> 00:00:04.000
Good morning everyone

00:00:04.000 --> 00:00:05.000
everyone
"""
    result = parse_srt_vtt(source)
    assert [(cue.start_ms, cue.end_ms, cue.text) for cue in result] == [
        (0, 2000, "Good morning"), (2000, 4000, "everyone"), (4000, 5000, "everyone"),
    ]


def test_bilibili_json_and_sorted_timestamps():
    result = parse_bilibili_json('{"body": [{"from": 3, "to": 4, "content": "第二句"}, {"from": 0.1, "to": 1.2, "content": "第一句"}]}')
    assert [(s.start_ms, s.text) for s in result] == [(100, "第一句"), (3000, "第二句")]


def test_empty_transcript_is_error():
    with pytest.raises(SubtitleUnavailableError):
        parse_srt_vtt("WEBVTT\n")
    with pytest.raises(SubtitleUnavailableError):
        parse_bilibili_json('{"body": []}')


def test_invalid_bilibili_content():
    with pytest.raises(ExtractionError):
        parse_bilibili_json('{"foo": []}')
    with pytest.raises(ExtractionError):
        parse_bilibili_json('{"body": [{"from": "x", "to": 1, "content": "x"}]}')
